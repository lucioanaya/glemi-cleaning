create or replace function public.handle_glemi_auth_user()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_email text := lower(coalesce(new.email,''));
  v_role text;
  v_name text;
begin
  if v_email='glemiservices@gmail.com' then
    v_role := 'owner';
    v_name := coalesce(new.raw_user_meta_data->>'display_name','Yolanda');
  elsif v_email='baltazaranaya@outlook.com' then
    v_role := 'admin';
    v_name := coalesce(new.raw_user_meta_data->>'display_name','Baltazar');
  else
    return new;
  end if;

  insert into public.profiles(id,email,display_name,role,active)
  values(new.id,v_email,v_name,v_role,true)
  on conflict(id) do update set
    email=excluded.email,
    display_name=coalesce(public.profiles.display_name,excluded.display_name),
    role=excluded.role,
    active=true;
  return new;
end;
$$;

