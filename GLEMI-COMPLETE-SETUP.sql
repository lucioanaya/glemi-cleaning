-- 9) Public calendar availability RPC
create or replace function public.get_calendar_availability(p_start_date date, p_end_date date)
returns table(
  day date,
  enabled boolean,
  start_time time,
  end_time time,
  booking_count bigint,
  booked_times text[]
)
language sql
stable
security definer
set search_path=public
as $$
with dates as (
  select d::date as day
  from generate_series(p_start_date::timestamp,p_end_date::timestamp,interval '1 day') d
), mapped as (
  select day,
    case extract(dow from day)::int
      when 0 then 'Sun' when 1 then 'Mon' when 2 then 'Tue' when 3 then 'Wed'
      when 4 then 'Thu' when 5 then 'Fri' when 6 then 'Sat' end as day_key
  from dates
)
select
  m.day,
  coalesce(s.enabled,false) as enabled,
  coalesce(s.start_time,'08:00'::time) as start_time,
  coalesce(s.end_time,'17:00'::time) as end_time,
  count(a.id) filter (where a.status <> 'cancelled')::bigint as booking_count,
  coalesce(array_agg(to_char(a.appointment_time,'HH24:MI') order by a.appointment_time)
    filter (where a.status <> 'cancelled' and a.appointment_time is not null), array[]::text[]) as booked_times
from mapped m
left join public.schedule_settings s on s.day_key=m.day_key
left join public.appointments a on a.appointment_date=m.day
  and a.status <> 'cancelled'
group by m.day,s.enabled,s.start_time,s.end_time
order by m.day;
$$;

grant execute on function public.get_calendar_availability(date,date) to anon, authenticated;

-- 10) Promo eligibility RPC
create or replace function public.check_promo_eligibility(p_code text, p_email text default null, p_phone text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path=public
as $$
declare
  v_code text := upper(trim(coalesce(p_code,'')));
  v_email text := lower(trim(coalesce(p_email,'')));
  v_phone text := regexp_replace(coalesce(p_phone,''),'\\D','','g');
  v_promo public.promo_codes%rowtype;
begin
  if v_email='' and v_phone='' then
    return jsonb_build_object('eligible',false,'reason','contact_required');
  end if;
  select * into v_promo from public.promo_codes where code=v_code and active=true;
  if not found then return jsonb_build_object('eligible',false,'reason','invalid_code'); end if;

  if exists(select 1 from public.promo_redemptions r where r.code=v_code and
    ((v_email<>'' and r.email_norm=v_email) or (v_phone<>'' and r.phone_norm=v_phone))) then
    return jsonb_build_object('eligible',false,'reason','already_used');
  end if;

  if v_promo.first_booking_only and exists(
    select 1 from public.appointments a where a.status <> 'cancelled' and
      ((v_email<>'' and lower(coalesce(a.email,''))=v_email) or
       (v_phone<>'' and regexp_replace(coalesce(a.phone,''),'\\D','','g')=v_phone))
  ) then
    return jsonb_build_object('eligible',false,'reason','existing_customer');
  end if;

  return jsonb_build_object('eligible',true,'code',v_code,'discount_percent',v_promo.discount_percent);
end;
$$;

grant execute on function public.check_promo_eligibility(text,text,text) to anon, authenticated;

-- 11) Public residential booking RPC
create or replace function public.create_residential_booking(
  p_client_name text,
  p_date date,
  p_time text,
  p_email text,
  p_phone text,
  p_address text,
  p_original_total numeric,
  p_discount_code text default null,
  p_quote_details jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path=public
as $$
declare
  v_time time;
  v_day_key text;
  v_schedule public.schedule_settings%rowtype;
  v_count int;
  v_discount numeric := 0;
  v_code text := upper(trim(coalesce(p_discount_code,'')));
  v_elig jsonb;
  v_final numeric(10,2);
  v_id bigint;
  v_email text := lower(trim(coalesce(p_email,'')));
  v_phone text := regexp_replace(coalesce(p_phone,''),'\\D','','g');
begin
  if trim(coalesce(p_client_name,''))='' or trim(coalesce(p_address,''))='' then
    return jsonb_build_object('ok',false,'reason','missing_required');
  end if;
  if v_email='' and v_phone='' then return jsonb_build_object('ok',false,'reason','contact_required'); end if;
  if p_date is null or p_date < current_date then return jsonb_build_object('ok',false,'reason','invalid_date'); end if;

  begin
    v_time := to_timestamp(trim(p_time),'HH12:MI AM')::time;
  exception when others then
    begin v_time := trim(p_time)::time; exception when others then
      return jsonb_build_object('ok',false,'reason','invalid_time');
    end;
  end;

  if v_time not in ('09:00'::time,'10:00'::time,'12:00'::time,'14:00'::time,'16:00'::time) then
    return jsonb_build_object('ok',false,'reason','invalid_time');
  end if;

  v_day_key := case extract(dow from p_date)::int
    when 0 then 'Sun' when 1 then 'Mon' when 2 then 'Tue' when 3 then 'Wed'
    when 4 then 'Thu' when 5 then 'Fri' when 6 then 'Sat' end;
  select * into v_schedule from public.schedule_settings where day_key=v_day_key;
  if not found or not v_schedule.enabled then return jsonb_build_object('ok',false,'reason','day_unavailable'); end if;
  if v_time < v_schedule.start_time or v_time >= v_schedule.end_time then return jsonb_build_object('ok',false,'reason','time_unavailable'); end if;

  select count(*) into v_count from public.appointments
  where appointment_date=p_date and status <> 'cancelled';
  if v_count>=5 then return jsonb_build_object('ok',false,'reason','day_full'); end if;
  if exists(select 1 from public.appointments where appointment_date=p_date and appointment_time=v_time and status <> 'cancelled') then
    return jsonb_build_object('ok',false,'reason','time_unavailable');
  end if;

  if v_code<>'' then
    v_elig := public.check_promo_eligibility(v_code,nullif(v_email,''),nullif(p_phone,''));
    if coalesce((v_elig->>'eligible')::boolean,false)=false then
      return jsonb_build_object('ok',false,'reason',v_elig->>'reason');
    end if;
    v_discount := coalesce((v_elig->>'discount_percent')::numeric,0);
  end if;

  v_final := round((greatest(coalesce(p_original_total,0),0) * (1-v_discount/100.0))::numeric,2);

  insert into public.appointments(
    client_name,service,appointment_date,appointment_time,phone,email,address,
    original_total_cad,total_cad,discount_code,discount_percent,quote_details,status
  ) values (
    trim(p_client_name),'Residential Cleaning',p_date,v_time,nullif(trim(coalesce(p_phone,'')),''),
    nullif(trim(coalesce(p_email,'')),''),trim(p_address),coalesce(p_original_total,0),v_final,
    nullif(v_code,''),v_discount,p_quote_details,'pending'
  ) returning id into v_id;

  if v_code<>'' and v_discount>0 then
    insert into public.promo_redemptions(code,appointment_id,email_norm,phone_norm)
    values(v_code,v_id,nullif(v_email,''),nullif(v_phone,''));
  end if;

  return jsonb_build_object(
    'ok',true,
    'appointment_id',v_id,
    'final_total',v_final,
    'discount_code',nullif(v_code,''),
    'discount_percent',v_discount
  );
end;
$$;

grant execute on function public.create_residential_booking(text,date,text,text,text,text,numeric,text,jsonb) to anon, authenticated;

